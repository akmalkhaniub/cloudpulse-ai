/**
 * Amazon Bedrock Converse API Client & Agentic Tool Orchestrator
 * Implements the unified Converse API standard on Amazon Bedrock (default model: Amazon Nova Pro):
 * - Standard Converse payload (messages, system, toolConfig, inferenceConfig)
 * - Native Bedrock tool calling (toolSpec, toolUse, toolResult) with a real
 *   tool-use loop against bedrock-runtime
 * - Mock/simulator fallback for offline environments without AWS credentials
 */
import { IaCParser } from './iac_parser.js';
import { WellArchitectedEngine, type AuditReport } from './well_architected_engine.js';
import { RemediationSynthesizer, type RemediationPatch } from './remediation_synthesizer.js';
import type { ChangeRisk } from './change_safety.js';

export interface ChangeBriefInput {
  shippedRisks: ChangeRisk[];
  heldBackRisks: ChangeRisk[];
  monthlySavingsUSD: number;
  verification: { findingsBefore: number; findingsAfter: number };
}

export interface ChangeBrief {
  title: string;
  markdown: string;
  /** Who wrote the narrative part: the model, or the deterministic template fallback. */
  narrativeSource: 'bedrock' | 'template';
  modelId?: string;
  latencyMs: number;
}

const LEVEL_ICON: Record<string, string> = { SAFE: '🟢 SAFE', CAUTION: '🟡 CAUTION', DISRUPTIVE: '🔴 DISRUPTIVE' };

/** The facts table is always generated by code, so the model can never drop or invent a risk. */
export function riskTableMarkdown(risks: ChangeRisk[]): string {
  if (!risks.length) return '_None._';
  const rows = risks.map((r) => `| \`${r.ruleId}\` | ${LEVEL_ICON[r.level]} | ${r.applyBehavior} | ${r.downtime} | ${r.guardsAdded.join('; ') || '—'} |`);
  return ['| Rule | Risk | How AWS applies it | Downtime | Guards added to the patch |', '| :--- | :--- | :--- | :--- | :--- |', ...rows].join('\n');
}

function checklistMarkdown(risks: ChangeRisk[]): string {
  const items = risks.flatMap((r) => r.beforeYouMerge.map((b) => `- [ ] **${r.ruleId}:** ${b}`));
  return items.length ? items.join('\n') : '- [ ] Review the diff.';
}

export interface AgentOptions {
  modelId?: string;
  region?: string;
  isMock?: boolean;
}

export interface ConverseResult {
  modelId: string;
  stopReason: string;
  output: { message: { role: string; content: Array<{ text?: string; [k: string]: unknown }> } };
  toolCalls: Array<{ id: string; name: string; input: Record<string, unknown> }>;
  toolResults: Array<{ toolUseId: string; content: Array<{ json: unknown }> }>;
  audit: AuditReport;
  patches: RemediationPatch[];
  usage: { inputTokens: number; outputTokens: number; totalTokens: number };
}

export class BedrockConverseAgent {
  modelId: string;
  region: string;
  isMock: boolean;
  toolConfig: { tools: Array<{ toolSpec: { name: string; description: string; inputSchema: { json: unknown } } }> };
  systemPrompt: Array<{ text: string }>;

  constructor(options: AgentOptions = {}) {
    this.modelId = options.modelId || process.env.BEDROCK_MODEL_ID || 'amazon.nova-pro-v1:0';
    this.region = options.region || process.env.AWS_REGION || 'us-east-1';
    const hasAwsEnv = Boolean(process.env.AWS_ACCESS_KEY_ID || process.env.AWS_PROFILE);
    this.isMock = options.isMock ?? (process.env.MOCK_BEDROCK === 'true' ? true : !hasAwsEnv && process.env.LIVE_BEDROCK !== 'true');

    this.toolConfig = {
      tools: [
        {
          toolSpec: {
            name: 'audit_iac_manifest',
            description: 'Audits Terraform or OpenTofu HCL code against AWS Well-Architected Pillars (Security, FinOps, Reliability).',
            inputSchema: { json: { type: 'object', properties: { hclContent: { type: 'string', description: 'Raw HCL Terraform code to inspect' } }, required: ['hclContent'] } }
          }
        },
        {
          toolSpec: {
            name: 'synthesize_remediation_diff',
            description: 'Synthesizes a compliant unified git diff to remediate an AWS Well-Architected finding.',
            inputSchema: { json: { type: 'object', properties: { ruleId: { type: 'string', description: 'Rule identifier e.g. SEC_OPEN_SSH_INGRESS' }, hclContent: { type: 'string', description: 'Original Terraform HCL code' } }, required: ['ruleId', 'hclContent'] } }
          }
        },
        {
          toolSpec: {
            name: 'estimate_finops_savings',
            description: 'Sums monthlySavingsUSD from the local us-east-1 price table. Not a live Price List API call.',
            inputSchema: { json: { type: 'object', properties: { violations: { type: 'array', description: 'Array of audit findings' } }, required: ['violations'] } }
          }
        }
      ]
    };

    this.systemPrompt = [
      { text: 'You are CloudPulse AI, an autonomous Senior AWS Cloud Architect and DevSecOps Agent powered by Amazon Bedrock. Your role is to inspect IaC manifests, detect Well-Architected violations, calculate FinOps ROI, and synthesize safe unified git diffs. Never describe a change as zero-downtime unless it is applied in place.' }
    ];
  }

  /** Execute a Bedrock Converse conversation turn with a tool-calling loop. */
  async runConverseTurn(userPrompt: string, hclContent = ''): Promise<ConverseResult> {
    const messages = [
      {
        role: 'user',
        content: [
          { text: userPrompt },
          ...(hclContent ? [{ text: `\nTerraform Manifest:\n\`\`\`hcl\n${hclContent}\n\`\`\`` }] : [])
        ]
      }
    ];

    if (this.isMock) return this.simulateConverseResponse(hclContent);

    try {
      const { BedrockRuntimeClient, ConverseCommand } = await import('@aws-sdk/client-bedrock-runtime');
      const client = new BedrockRuntimeClient({ region: this.region });
      const command = new ConverseCommand({
        modelId: this.modelId,
        messages: messages as any,
        system: this.systemPrompt as any,
        toolConfig: this.toolConfig as any,
        inferenceConfig: { maxTokens: 4096, temperature: 0.1, topP: 0.9 }
      });
      const response = await client.send(command);
      return await this.processBedrockResponse(response, client, ConverseCommand, messages, hclContent);
    } catch (err) {
      console.warn('⚠️ [Bedrock Converse] Falling back to intelligent simulator mode:', (err as Error).message);
      return this.simulateConverseResponse(hclContent);
    }
  }

  /**
   * Handle a live Bedrock Converse response: run any requested tool_use blocks,
   * feed toolResult blocks back for a final turn, and normalize to ConverseResult.
   */
  /* c8 ignore start -- live Bedrock tool-use loop; runs only with real AWS credentials */
  async processBedrockResponse(response: any, client: any, ConverseCommand: any, messages: any[], hclContent: string): Promise<ConverseResult> {
    const toolCalls: ConverseResult['toolCalls'] = [];
    const toolResults: ConverseResult['toolResults'] = [];

    let current = response;
    let guard = 0;
    while (current?.stopReason === 'tool_use' && guard++ < 5) {
      const assistantContent: any[] = current.output?.message?.content || [];
      // Echo the assistant's tool_use turn back into the conversation.
      messages.push({ role: 'assistant', content: assistantContent });

      const toolResultBlocks: any[] = [];
      for (const block of assistantContent) {
        if (!block.toolUse) continue;
        const { toolUseId, name, input } = block.toolUse;
        toolCalls.push({ id: toolUseId, name, input });
        const result = this.executeTool(name, input || {});
        toolResults.push({ toolUseId, content: [{ json: result }] });
        toolResultBlocks.push({ toolResult: { toolUseId, content: [{ json: result }] } });
      }

      messages.push({ role: 'user', content: toolResultBlocks });
      current = await client.send(
        new ConverseCommand({
          modelId: this.modelId,
          messages,
          system: this.systemPrompt,
          toolConfig: this.toolConfig,
          inferenceConfig: { maxTokens: 4096, temperature: 0.1, topP: 0.9 }
        })
      );
    }

    // Derive the same structured audit/patches the UI expects, locally.
    const resources = IaCParser.parse(hclContent);
    const audit = WellArchitectedEngine.audit(resources);
    const patches = audit.findings.map((f) => RemediationSynthesizer.generatePatch(f, hclContent));
    const usage = current?.usage || {};

    return {
      modelId: this.modelId,
      stopReason: current?.stopReason || 'end_turn',
      output: current?.output || { message: { role: 'assistant', content: [{ text: '' }] } },
      toolCalls,
      toolResults,
      audit,
      patches,
      usage: {
        inputTokens: usage.inputTokens || 0,
        outputTokens: usage.outputTokens || 0,
        totalTokens: usage.totalTokens || (usage.inputTokens || 0) + (usage.outputTokens || 0)
      }
    };
  }
  /* c8 ignore stop */

  /**
   * Ask the model to write the human part of the pull request (summary + rollout plan) from structured facts.
   * Falls back to a deterministic template without credentials or on any error.
   */
  async writeChangeBrief(input: ChangeBriefInput): Promise<ChangeBrief> {
    const started = Date.now();
    const all = [...input.shippedRisks, ...input.heldBackRisks];
    const title = input.heldBackRisks.length
      ? `CloudPulse: ${input.shippedRisks.length} safe fix(es) now, ${input.heldBackRisks.length} held for approval`
      : `CloudPulse: remediate ${input.shippedRisks.length} Well-Architected finding(s)`;

    const facts = [
      '## Risk assessment (generated by the CloudPulse safety engine)',
      riskTableMarkdown(input.shippedRisks),
      input.heldBackRisks.length ? '\n## Held back — needs human approval\n' + riskTableMarkdown(input.heldBackRisks) : '',
      '\n## Before you merge',
      checklistMarkdown(input.shippedRisks),
      `\n## Verification\nRe-audited the patched manifest: **${input.verification.findingsBefore} → ${input.verification.findingsAfter}** findings for the rules in this PR.`
    ].filter(Boolean).join('\n');

    const template = [
      '## Summary',
      `This PR applies ${input.shippedRisks.length} infrastructure fix(es)` +
        (input.monthlySavingsUSD > 0 ? `, saving about $${input.monthlySavingsUSD.toFixed(2)}/month at list price` : '') + '.',
      input.heldBackRisks.length ? `${input.heldBackRisks.length} disruptive change(s) were held back until a human approves them.` : '',
      '\n## Rollout plan',
      '1. Run `terraform plan` and confirm only the resources listed below change.',
      '2. Apply outside peak hours.',
      '3. Re-run CloudPulse to confirm the findings are resolved.'
    ].filter(Boolean).join('\n');

    if (this.isMock) {
      return { title, markdown: `${template}\n\n${facts}`, narrativeSource: 'template', latencyMs: Date.now() - started };
    }

    try {
      const { BedrockRuntimeClient, ConverseCommand } = await import('@aws-sdk/client-bedrock-runtime');
      const client = new BedrockRuntimeClient({ region: this.region });
      const prompt =
        'Write the "## Summary" and "## Rollout plan" sections of a GitHub pull request description for these Terraform changes. ' +
        'Use ONLY the facts in the JSON. Be specific and concise (under 180 words). Explain the risk in plain English for a reviewer, ' +
        'order the rollout so the safest changes go first, and mention any guard or approval explicitly. Do not add a title. ' +
        'Do not repeat the facts as a table.\n\n' + JSON.stringify(input, null, 2);
      const response: any = await client.send(new ConverseCommand({
        modelId: this.modelId,
        system: [{ text: 'You are a senior AWS platform engineer writing pull request descriptions. You never invent facts.' }] as any,
        messages: [{ role: 'user', content: [{ text: prompt }] }] as any,
        inferenceConfig: { maxTokens: 600, temperature: 0.2 }
      }));
      const text: string = (response?.output?.message?.content || []).map((c: any) => c.text || '').join('').trim();
      if (text.length < 40) throw new Error('empty model output');
      return { title, markdown: `${text}\n\n${facts}`, narrativeSource: 'bedrock', modelId: this.modelId, latencyMs: Date.now() - started };
    } catch (err) {
      console.warn('⚠️ [Bedrock Converse] Change brief fell back to template:', (err as Error).message);
      return { title, markdown: `${template}\n\n${facts}`, narrativeSource: 'template', latencyMs: Date.now() - started };
    }
  }

  /** Dispatch and handle Bedrock tool execution. */
  executeTool(toolName: string, toolInput: Record<string, any>): unknown {
    if (toolName === 'audit_iac_manifest') {
      const resources = IaCParser.parse(toolInput.hclContent);
      const audit = WellArchitectedEngine.audit(resources);
      return {
        resourcesParsed: resources.length,
        violationsCount: audit.violationsCount,
        findings: audit.findings,
        totalMonthlySavingsUSD: audit.totalMonthlySavingsUSD
      };
    }
    if (toolName === 'synthesize_remediation_diff') {
      return RemediationSynthesizer.generatePatch({ ruleId: toolInput.ruleId, resourceId: toolInput.resourceId }, toolInput.hclContent);
    }
    if (toolName === 'estimate_finops_savings') {
      const totalSavings = (toolInput.violations || []).reduce((acc: number, v: any) => acc + (v.monthlySavingsUSD || 0), 0);
      return {
        projectedMonthlySavingsUSD: totalSavings,
        annualizedSavingsUSD: Math.round(totalSavings * 12 * 100) / 100,
        priceTable: 'local us-east-1 on-demand table, not the AWS Price List API'
      };
    }
    throw new Error(`Unknown tool: ${toolName}`);
  }

  /** Deterministic simulation adhering to the Bedrock Converse schema. */
  simulateConverseResponse(hclContent: string): ConverseResult {
    const resources = IaCParser.parse(hclContent);
    const audit = WellArchitectedEngine.audit(resources);
    const toolUseId = 'tooluse_' + Math.random().toString(36).substring(2, 9);
    const toolResult = this.executeTool('audit_iac_manifest', { hclContent });
    const patches = audit.findings.map((f) => RemediationSynthesizer.generatePatch(f, hclContent));

    // Derive the summary from the ACTUAL audit (no hardcoded claims).
    const criticals = audit.findings.filter((f) => f.severity === 'CRITICAL').length;
    const annual = Math.round(audit.totalMonthlySavingsUSD * 12 * 100) / 100;
    const securityLine = criticals > 0
      ? `**${criticals} critical finding${criticals === 1 ? '' : 's'}** (highest severity across Security pillar).`
      : `no critical findings.`;

    return {
      modelId: this.modelId,
      stopReason: 'end_turn',
      output: {
        message: {
          role: 'assistant',
          content: [
            {
              text: `### CloudPulse AI Audit Summary (Amazon Bedrock Converse API — simulator)\n\nI parsed **${resources.length} infrastructure resources** and identified **${audit.violationsCount} AWS Well-Architected violations** across Security, FinOps, and Reliability.\n\n- **Projected FinOps Savings:** $${audit.totalMonthlySavingsUSD}/month ($${annual}/year)\n- **Security Posture:** ${securityLine}\n- **Remediation Status:** ${patches.filter((p) => p.autoFixable).length} patch${patches.filter((p) => p.autoFixable).length === 1 ? '' : 'es'} synthesized, each with a blast-radius assessment.`
            }
          ]
        }
      },
      toolCalls: [{ id: toolUseId, name: 'audit_iac_manifest', input: { hclContent } }],
      toolResults: [{ toolUseId, content: [{ json: toolResult }] }],
      audit,
      patches,
      // Simulator: no live model call was made, so there is no real token usage to report.
      usage: { inputTokens: 0, outputTokens: 0, totalTokens: 0 }
    };
  }
}
